import type { Effect, FoeDef } from './types';

export type FateKey = 'fang' | 'wen' | 'sha';

export interface Fate {
  /** 选了以后，战斗记录里的一段话 */
  say: string;
  /** 换掉对手原来结算的标题和叙述（原来的结算替玩家定了别的结局时） */
  title?: string;
  story?: string;
  /** 后果 */
  fx: Effect[];
  /** 结算页上的一句「以后」 */
  later: string;
}

export interface AftermathDef {
  /** 对手倒下以后说的话 */
  plea: string;
  fang: Fate;
  wen: Fate;
  sha: Fate;
}

