/** 这个对手打倒以后，问不问「放还是杀」：只问单独写了的 */
export function aftermathOf(f: FoeDef): AftermathDef | null {
  const d = AFTER[f.id];
  if (!d || f.spar || f.script) return null;
  const tag = (k: FateKey): Fate => ({ ...d[k], fx: [...d[k].fx, flag(f.id, k)] });
  return { plea: d.plea, fang: tag('fang'), wen: tag('wen'), sha: tag('sha') };
}

