import type { EnvironmentMood, TerrainId, ThemeId } from '../contracts';

export type TreeKind = 'broadleaf' | 'conifer' | 'snowpine' | 'dead' | 'autumn';
export type ParticleKind = 'embers' | 'leaves' | 'fireflies' | 'pollen' | 'snow' | 'rain' | 'ash' | 'motes' | 'spray';

export interface ParticleSpec {
  kind: ParticleKind;
  count: number;
  color: string;
  size: number;
}

export interface ThemeConfig {
  sky: { top: string; horizon: string; bottom: string; sunGlow: string };
  /** 指向太阳/月亮的方向 */
  sunDir: [number, number, number];
  sunColor: string;
  sunIntensity: number;
  /** 天空中显示：sun / moon / eclipse / none */
  disc: 'sun' | 'moon' | 'eclipse' | 'none';
  stars: number;
  clouds: number;
  cloudColor: string;
  hemi: { sky: string; ground: string; intensity: number };
  fog: { color: string; near: number; far: number };
  /** 地面主色（草地/土地） */
  ground: [string, string];
  dirt: string;
  rock: string;
  sand: string;
  snowCover: number; // 0..1 地表积雪程度
  floor: string;
  wallStone: string;
  roof: string[];
  plaster: string;
  water: { shallow: string; deep: string };
  lava: string;
  trees: TreeKind[];
  foliage: string[];
  grass: number; // 草丛密度 0..1
  flowers: string[];
  particles: ParticleSpec[];
  /** 是否在城墙/城门处放置火盆 */
  braziers: boolean;
  /** 地图外延的地形 */
  outer: { base: TerrainId; features: [TerrainId, number][] };
  /** 额外补光（火光等） */
  fill?: { color: string; intensity: number };
  mood: EnvironmentMood;
}

const m = (exposure: number, bloomStrength: number, bloomThreshold: number, vignette: number, tint: string, saturation = 1, contrast = 1, bloomRadius = 0.55): EnvironmentMood => ({
  exposure,
  bloomStrength,
  bloomRadius,
  bloomThreshold,
  vignette,
  tint,
  saturation,
  contrast,
});

